"""
天气顾问 Agent（wather.py）
==========================

在 min_react_agent.py 的通用循环之上，只写"差异化"的部分：
    1. 一段天气顾问的系统提示词（人设 + 工具暗号 + 四段式输出契约）；
    2. 一个命令行入口。

通用部分（工具注册表、ask_llm、parse_tool_calls、主循环）全部 import 复用，
一行不改。这就是项目长大的方式：通用能力沉到底层，新需求只写新文案。

运行（Git Bash，venv 已激活，Ollama 已启动）：
    python examples/wather.py 洛阳
    python examples/wather.py 哈尔滨
"""

import sys

from min_react_agent import run_agent

# ============================================================
# 系统提示词 = Agent 的"岗位说明书"
# ============================================================
# 三件事必须写全，缺一个循环就转不动：
#   1. 人设：它是谁（决定语气和知识角度）；
#   2. 工具暗号：怎么调工具（不写 JSON 契约，循环永远只思考不行动）；
#   3. 输出契约：最终答案长什么样（四段式，用户每次拿到的都是稳定格式）。

SYSTEM_PROMPT = """你是用户的天气顾问，擅长把天气数据翻译成穿衣、户外、洗车等生活建议。

工作流程：
1. 用户提到一个地方时，先只输出一行 JSON 调用工具：
   {"tool": "get_weather", "args": {"city": "城市名"}}
2. 拿到工具返回的真实天气后，严格按下面四段式输出：

[天气实况] 城市、当前天气、气温
[穿衣建议] 具体穿什么、要不要带雨具或防晒
[户外建议] 适不适合户外活动、注意什么
[洗车建议] 适不适合洗车、为什么

纪律：
- 没拿到工具结果前，不许编造任何天气数据。
- 语气像朋友聊天，每段一到两句话，不写小作文。
- 四段一个都不能少，段头格式原样保留。"""


if __name__ == "__main__":
    # 和上一个文件一样：命令行第一个参数就是要查的地方
    city = sys.argv[1] if len(sys.argv) > 1 else "洛阳"
    print(f"[天气顾问] 收到，查询 {city} ...")
    answer = run_agent(f"{city}今天天气怎么样？适合洗车吗？", system_prompt=SYSTEM_PROMPT)
    print(f"\n[最终建议]\n{answer}")
